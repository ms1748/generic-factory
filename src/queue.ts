// The build queue, worked out exactly as the builder prompt does (docs/factory/prompts/builder.md and
// common.md in the project): open `ready` issues, minus building/review/hold/needs-owner, blocked cards
// and cards with an open PR; ordered p1 > p2 > p3 > none, then lowest issue number. Pure: no I/O (the
// marker reads the install's settings only).
import type { Lane } from "./config.ts";
import { install } from "./install.ts";

export interface Comment {
  author: string;
  body: string;
}

export interface Issue {
  number: number;
  title: string;
  labels: string[];
  body: string;
  comments: Comment[];
  /** GitHub's own "blocked by" relationships, when the repo uses them. */
  blockedBy: number[];
}

export interface Pull {
  number: number;
  title: string;
  draft: boolean;
  branch: string;
  body: string;
  labels: string[];
  updatedAt?: string;
}

export type CardState = "queued" | "skipped";

export interface Card {
  number: number;
  /** The repo the card lives in, when the factory works on several (set by the dispatcher). */
  repo?: string;
  title: string;
  size: string | null;
  priority: string | null;
  state: CardState;
  /** Why it's skipped, in a few plain words. */
  reason?: string;
  /** An open draft PR on `claude/issue-<n>-*`: the builder continues there. */
  draftPr?: number;
  blockers: number[];
}

export const EXCLUDED = ["building", "review", "hold", "needs-owner"];
export const PRIORITIES = ["p1", "p2", "p3"];

export const sizeOf = (labels: string[]) => labels.find((l) => l.startsWith("size:"))?.slice(5) ?? null;
export const priorityOf = (labels: string[]) => PRIORITIES.find((p) => labels.includes(p)) ?? null;

/** The footer agents end their comments with. The project's prompt files use the same text (a contract). */
export const MARKER = "<!-- factory -->";
/**
 * The marker, or any of the older names that comments already on GitHub carry (Settings › Install,
 * `legacyMarkers`; none by default).
 */
export function markers(legacy: string[] = install().legacyMarkers): RegExp {
  const names = ["factory", ...legacy].map((n) => n.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));
  return new RegExp(`<!-- (?:${names.join("|")}) -->`, "g");
}

/** Whether a comment or body carries the agents' marker, new or old. */
export const hasMarker = (body: string, legacy?: string[]): boolean => new RegExp(markers(legacy).source).test(body);
/** The text with every marker, new or old, taken out. */
export const stripMarker = (body: string, legacy?: string[]): string => body.replace(markers(legacy), "");

/** Agent comments carry the marker (or Claude Code's footer); everything else is the owner's. */
export function isAgent(c: Comment): boolean {
  return c.author.endsWith("[bot]") || hasMarker(c.body) || /Generated by \[Claude Code\]/.test(c.body);
}

/** Issue numbers named after "Blocked by", "Blocked on", "Waits on" or "Depends on". */
export function blockersIn(text: string): number[] {
  const out = new Set<number>();
  for (const m of text.matchAll(/\b(?:blocked\s+(?:by|on)|waits\s+on|depends\s+on)\s*:?\s*((?:#\d+(?:\s*(?:,|and|&)\s*)?)+)/gi)) {
    for (const n of m[1].matchAll(/#(\d+)/g)) out.add(Number(n[1]));
  }
  return [...out];
}

/** The issue a PR works on: its `claude/issue-<n>-*` branch, else a "Closes #n" line. */
export function issueOfPull(p: Pull): number | undefined {
  const branch = p.branch.match(/^claude\/issue-(\d+)-/);
  if (branch) return Number(branch[1]);
  const closes = p.body.match(/\b(?:close[sd]?|fix(?:e[sd])?|resolve[sd]?)\s+#(\d+)/i);
  return closes ? Number(closes[1]) : undefined;
}

/** Every `ready` card in build order, each queued or skipped with a reason. */
export function buildQueue(ready: Issue[], pulls: Pull[], openIssues: Set<number>): Card[] {
  const cards = ready.map((issue): Card => {
    const ownerText = [issue.body, ...issue.comments.filter((c) => !isAgent(c)).map((c) => c.body)].join("\n");
    const blockers = [...new Set([...issue.blockedBy, ...blockersIn(ownerText)])].filter((n) => openIssues.has(n) && n !== issue.number);
    const linked = pulls.filter((p) => issueOfPull(p) === issue.number);
    const openPr = linked.find((p) => !p.draft);
    const draft = linked.find((p) => p.draft && p.branch.startsWith(`claude/issue-${issue.number}-`));
    const excluded = EXCLUDED.find((l) => issue.labels.includes(l));
    const reason = excluded
      ? excluded
      : blockers.length
        ? `blocked by ${blockers.map((n) => "#" + n).join(", ")}`
        : openPr
          ? `PR #${openPr.number} is open`
          : undefined;
    return {
      number: issue.number,
      title: issue.title,
      size: sizeOf(issue.labels),
      priority: priorityOf(issue.labels),
      state: reason ? "skipped" : "queued",
      reason,
      draftPr: draft?.number,
      blockers,
    };
  });
  return cards.sort(byPriority);
}

const rank = (c: Card) => (c.priority ? PRIORITIES.indexOf(c.priority) : PRIORITIES.length);
/** Queue order: priority first, then the older card. Stable, so merged queues keep each repo's order on ties. */
export const byPriority = (a: Card, b: Card): number => rank(a) - rank(b) || a.number - b.number;

export interface Pick {
  card?: Card;
  action?: "build" | "continue" | "split";
  /** Why the lane would do nothing. */
  idle?: string;
}

/** What a builder lane would take on its next run. `maxOpenPrs` 0 means no open-PR limit. */
export function pickFor(lane: Lane, queue: Card[], openFactoryPrs: number, maxOpenPrs: number): Pick {
  if (maxOpenPrs > 0 && openFactoryPrs >= maxOpenPrs) return { idle: `${openFactoryPrs} factory PRs are open (limit ${maxOpenPrs})` };
  const card = queue.find((c) => c.state === "queued" && takes(lane, c));
  if (!card) return { idle: "no queued card fits this lane" };
  const action = lane.splits.includes(card.size ?? "none") ? "split" : card.draftPr ? "continue" : "build";
  return { card, action };
}

export function takes(lane: Lane, c: Card): boolean {
  const size = c.size ?? "none";
  return lane.sizes.includes(size) || lane.splits.includes(size);
}
